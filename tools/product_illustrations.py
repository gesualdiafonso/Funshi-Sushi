def roll_slice(r, kind, fillings, outer_dots=('#f6ecd8', '#2a2018')):
    """Top view of one slice, radius ~120, centred on 0,0."""
    parts = ['<ellipse cx="14" cy="22" rx="132" ry="128" fill="#000" opacity="0.55" filter="url(#contact)"/>']
    if kind == 'hot':
        crumbs = dots(r, 90, 104, 124, ['#f3cd80', '#a8621f', '#e0a352'], 7, 5)
        parts += ['<circle r="126" fill="url(#crust)"/>', crumbs,
                  '<circle r="102" fill="url(#rice-top)"/>', rice_grains(r, 55, 68, 98)]
        nori_r, fill_r = 64, 57
    else:
        parts += ['<circle r="120" fill="url(#rice-top)"/>', rice_grains(r, 80, 80, 116),
                  dots(r, 34, 84, 116, list(outer_dots))]
        nori_r, fill_r = 72, 65
    parts += [f'<circle r="{nori_r}" fill="url(#nori)"/>', f'<circle r="{fill_r}" fill="#efe7da"/>',
              rice_grains(r, 14, 40, fill_r - 6)]
    scale = 1.2 if kind == 'hot' else 1.35  # fill the centre of the slice
    parts.append(f'<g transform="scale({scale})">' + ''.join(FILLING[f] for f in fillings) + '</g>')
    return ''.join(parts)


def drizzle(color, width=10):
    return (f'<path d="M 170 330 C 260 290, 330 400, 420 360 S 560 300, 640 370 S 780 420, 840 360" '
            f'stroke="{color}" stroke-width="{width}" fill="none" stroke-linecap="round" opacity="0.92"/>'
            f'<path d="M 230 640 C 320 600, 400 700, 500 660 S 660 600, 760 680" '
            f'stroke="{color}" stroke-width="{width}" fill="none" stroke-linecap="round" opacity="0.92"/>')


def roll_plate(r, kind, fillings, outer_dots=('#f6ecd8', '#2a2018'), sauce=None):
    body = board(r) + '\n'
    for (x, y, rot) in [(330, 390, -20), (660, 360, 15), (500, 660, 40)]:
        body += f'  <g transform="translate({x} {y}) rotate({rot}) scale(1.22)">{roll_slice(r, kind, fillings, outer_dots)}</g>\n'
    if sauce:
        body += '  ' + drizzle(sauce) + '\n'
    return body + wasabi(830, 790, 0.7)


