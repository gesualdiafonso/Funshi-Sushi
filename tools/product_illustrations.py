def shiso(x, y, rot):
    veins = ''.join(f'<path d="M {vx} 0 C {vx + 30} -40, {vx + 50} -70, {vx + 70} -90" />' for vx in range(-160, 140, 60))
    veins2 = ''.join(f'<path d="M {vx} 0 C {vx + 30} 40, {vx + 50} 70, {vx + 70} 90" />' for vx in range(-160, 140, 60))
    return f'''  <g transform="translate({x} {y}) rotate({rot})">
    <path d="M -240 0 C -160 -150, 140 -170, 250 0 C 140 170, -160 150, -240 0 Z" fill="#000" opacity="0.45" filter="url(#contact)" transform="translate(10 14)"/>
    <path d="M -240 0 C -160 -150, 140 -170, 250 0 C 140 170, -160 150, -240 0 Z" fill="url(#shiso)"/>
    <g fill="none" stroke="#8fc06a" stroke-width="4" opacity="0.6"><path d="M -240 0 L 250 0"/>{veins}{veins2}</g>
  </g>'''


def sashimi_plate(fishes, r):
    body = slate() + '\n' + shiso(470, 470, -24)
    n = len(fishes)
    for i, fish in enumerate(fishes):
        x = 380 + i * (300 / max(n - 1, 1))
        y = 300 + i * (360 / max(n - 1, 1))
        body += f'\n  <g transform="translate({x:.0f} {y:.0f}) rotate(-16)">{sashimi_slice(fish, r)}</g>'
    return body + '\n' + wasabi(790, 300, 0.75)


# ------------------------------------------------------------------- rolls
def rice_grains(r, n, r_in, r_out, color='#cfc3b1'):
    out = []
    for _ in range(n):
        import math
        a = r.uniform(0, 6.283)
        d = r.uniform(r_in, r_out)
        x, y = d * math.cos(a), d * math.sin(a)
        out.append(f'<ellipse cx="{x:.0f}" cy="{y:.0f}" rx="10" ry="4.5" transform="rotate({r.uniform(0, 180):.0f} {x:.0f} {y:.0f})" fill="#fbf8f2" stroke="{color}" stroke-width="1.2"/>')
    return ''.join(out)


def dots(r, n, r_in, r_out, colors, rx=5, ry=3):
    import math
    out = []
    for _ in range(n):
        a = r.uniform(0, 6.283)
        d = r.uniform(r_in, r_out)
        x, y = d * math.cos(a), d * math.sin(a)
        out.append(f'<ellipse cx="{x:.0f}" cy="{y:.0f}" rx="{rx}" ry="{ry}" transform="rotate({r.uniform(0, 180):.0f} {x:.0f} {y:.0f})" fill="{r.choice(colors)}"/>')
    return ''.join(out)


