def gunkan(r, topping):
    parts = ['<ellipse cx="14" cy="24" rx="160" ry="120" fill="#000" opacity="0.55" filter="url(#contact)"/>',
             '<ellipse rx="152" ry="112" fill="url(#nori)"/>',
             '<ellipse rx="152" ry="112" fill="none" stroke="#3c4b36" stroke-width="3" opacity="0.6"/>',
             '<ellipse rx="134" ry="94" fill="#efe7da"/>']
    if topping == 'roe':
        for _ in range(46):
            x, y = r.uniform(-112, 112), r.uniform(-74, 74)
            if (x / 120) ** 2 + (y / 82) ** 2 > 1:
                continue
            parts.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="17" fill="url(#roe)"/><circle cx="{x - 6:.0f}" cy="{y - 6:.0f}" r="4" fill="#fff" opacity="0.8"/>')
    else:
        for _ in range(26):
            x, y = r.uniform(-106, 106), r.uniform(-66, 66)
            if (x / 118) ** 2 + (y / 80) ** 2 > 1:
                continue
            parts.append(f'<rect x="{x - 20:.0f}" y="{y - 16:.0f}" width="40" height="32" rx="9" fill="url(#salmon)" transform="rotate({r.uniform(-40, 40):.0f} {x:.0f} {y:.0f})"/>')
        for _ in range(9):
            x, y = r.uniform(-90, 90), r.uniform(-56, 56)
            parts.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="8" fill="none" stroke="#86b850" stroke-width="4"/>')
    return ''.join(parts)


