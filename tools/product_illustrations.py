def nigiri_plate(fish, r):
    tail = '<use href="#slab-shrimp-tail"/>' if fish == 'shrimp' else ''
    pieces = ''
    for (x, y, rot) in [(470, 380, -10), (540, 650, -6)]:
        pieces += f'  <g transform="translate({x} {y}) rotate({rot}) scale(0.92)"><use href="#nigiri-{fish}"/>{tail}</g>\n'
    sesame = ''
    if fish == 'eel':
        sesame = ''.join(
            f'<ellipse cx="{r.uniform(-170, 170):.0f}" cy="{r.uniform(-38, 38):.0f}" rx="6" ry="3" fill="#f6ecd8"/>'
            for _ in range(14))
        pieces += f'  <g transform="translate(470 380) rotate(-10) scale(0.92)">{sesame}</g>\n'
        pieces += f'  <g transform="translate(540 650) rotate(-6) scale(0.92)">{sesame}</g>\n'
    return tray() + '\n' + pieces + (wasabi(820, 820) if fish != 'eel' else '')


