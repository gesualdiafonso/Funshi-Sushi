/**
 * Search and sharing metadata, generated from js/config.js and js/data/menu.js.
 * Pure functions (no file access) so they are unit-tested and the consistency
 * test can check that the pages are up to date. tools/build-seo.mjs writes the
 * result to disk.
 *
 * What it produces, and the rule for each:
 *  • Per page, between <!-- seo:start --> and <!-- seo:end -->:
 *      canonical URL, og:url and og:image  — only with a real site URL
 *                                            (they must be absolute; never invented)
 *      robots "noindex"                    — on index/menu while site.allowIndexing is false
 *      og:title / og:description           — copied from the page's own <title> and description
 *      JSON-LD                             — Restaurant (home), Menu (menu page, real menu only)
 *  • robots.txt (always) and sitemap.xml (only with a URL and indexing allowed).
 *
 * Structured data contains only facts present in the config or the menu data:
 * no ratings, reviews, price ranges or reservation claims, and nothing from the
 * sample menu.
 */

import { buildCatalog } from '../js/core/catalog.js';
import { DAYS } from '../js/core/hours.js';
import { minorDigits } from '../js/core/money.js';

export const START = '<!-- seo:start — generated by tools/build-seo.mjs from js/config.js; do not edit by hand -->';
export const END = '<!-- seo:end -->';

/**
 * The pages and how each is treated. `path` is the page's address relative to
 * the site URL ('' = the home page, so it is never indexed as /index.html).
 */
export const PAGES = [
  { file: 'index.html', path: '', indexable: true, jsonLd: 'restaurant' },
  { file: 'menu.html', path: 'menu.html', indexable: true, jsonLd: 'menu' },
  // 404: only a <base>, once the site URL is known. The checkout and the
  // design-system page carry a fixed noindex in their HTML and get nothing.
  { file: '404.html', path: null, indexable: false, notFound: true },
];

export const OG_IMAGE = { path: 'assets/brand/og-image.jpg', width: 1200, height: 630, alt: 'Funshi Sushi wordmark beside an illustration of three nigiri on a lacquered board.' };
const LOGO = 'assets/brand/icon-512.png';

const SCHEMA_DAYS = { mon: 'Monday', tue: 'Tuesday', wed: 'Wednesday', thu: 'Thursday', fri: 'Friday', sat: 'Saturday', sun: 'Sunday' };
const DIETS = { vegan: 'https://schema.org/VeganDiet', vegetarian: 'https://schema.org/VegetarianDiet' };

/**
 * The site URL from config, normalized to end with '/'; null when not set.
 * @throws if set but not an absolute http(s) URL
 */
export function siteBase(config) {
  const raw = config.site?.url;
  if (raw === null || raw === undefined || raw === '') return null;
  let url;
  try {
    url = new URL(String(raw));
  } catch {
    throw new Error(`config.site.url is not a valid URL: ${raw}`);
  }
  if (!/^https?:$/.test(url.protocol) || url.search || url.hash) {
    throw new Error(`config.site.url must be a plain http(s) address without ?query or #hash: ${raw}`);
  }
  if (!url.pathname.endsWith('/')) url.pathname += '/';
  return url.href;
}

export const absolute = (base, path) => new URL(path, base).href;

const escapeAttr = (value) => String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const decodeAttr = (value) => value.replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

/** JSON for a <script type="application/ld+json"> block, safe inside HTML. */
const jsonLdScript = (data) => `<script type="application/ld+json">${JSON.stringify(data, null, 2).replace(/</g, '\\u003c')}</script>`;

/** 'pt-BR' → 'pt_BR' (Open Graph locale format). */
const ogLocale = (locale) => (locale ? locale.replace('-', '_') : null);

/** Read the page's own title and description (the HTML stays the source for page text). */
export function pageText(html) {
  const title = html.match(/<title>([^<]*)<\/title>/)?.[1];
  const description = html.match(/<meta name="description" content="([^"]*)">/)?.[1];
  if (!title || !description) throw new Error('page needs a <title> and a <meta name="description">');
  return { title: decodeAttr(title), description: decodeAttr(description) };
}

/** schema.org Restaurant from the confirmed facts only. */
export function restaurantJsonLd(config, { base, isDemoMenu }) {
  const data = {
    '@context': 'https://schema.org',
    '@type': 'Restaurant',
    name: config.brandName,
    servesCuisine: ['Japanese', 'Sushi'],
  };
  if (base) {
    data.url = base;
    data.image = absolute(base, OG_IMAGE.path);
    data.logo = absolute(base, LOGO);
    if (!isDemoMenu) data.hasMenu = absolute(base, 'menu.html');
  }
  if (config.phone) data.telephone = config.phone;
  if (config.address) {
    const a = config.address;
    data.address = {
      '@type': 'PostalAddress',
      streetAddress: [a.street, a.area].filter(Boolean).join(', '),
      addressLocality: a.city,
      addressRegion: a.region,
      postalCode: a.postalCode,
      addressCountry: a.country,
    };
    for (const key of Object.keys(data.address)) if (!data.address[key]) delete data.address[key];
  }
  if (config.hours) {
    data.openingHoursSpecification = DAYS.flatMap((day) => (config.hours[day] ?? []).map(([opens, closes]) => ({
      '@type': 'OpeningHoursSpecification',
      dayOfWeek: `https://schema.org/${SCHEMA_DAYS[day]}`,
      opens,
      closes,
    })));
  }
  if (config.mapsUrl || config.social?.length) {
    data.sameAs = [config.mapsUrl, ...(config.social ?? []).map((link) => link.url)].filter(Boolean);
  }
  return data;
}

/**
 * schema.org Menu from the real menu: null for the sample menu (its prices
 * and dishes are not the restaurant's) or when the currency is unknown.
 */
export function menuJsonLd(menuData, config, { base }) {
  if (menuData.IS_DEMO_MENU || !config.currency) return null;
  const { catalog } = buildCatalog(menuData);
  const digits = minorDigits(config.currency);
  const price = (minor) => (minor / 10 ** digits).toFixed(digits);
  const offer = (minor, name) => ({
    '@type': 'Offer',
    ...(name ? { name } : {}),
    price: price(minor),
    priceCurrency: config.currency,
  });

  const sections = catalog.categories.map((category) => ({
    '@type': 'MenuSection',
    name: category.name,
    hasMenuItem: (catalog.byCategory.get(category.id) ?? []).map((product) => {
      const item = { '@type': 'MenuItem', name: product.name };
      if (product.description) item.description = product.description;
      if (base && product.slug) item.url = absolute(base, `menu.html?dish=${encodeURIComponent(product.slug)}`);
      const offers = product.variants?.length
        ? product.variants.filter((v) => Number.isSafeInteger(v.price)).map((v) => offer(v.price, v.label))
        : Number.isSafeInteger(product.price) ? [offer(product.price)] : [];
      if (offers.length) item.offers = offers.length === 1 ? offers[0] : offers;
      const diets = product.tags.map((tag) => DIETS[tag]).filter(Boolean);
      if (diets.length) item.suitableForDiet = diets;
      return item;
    }).filter(Boolean),
  })).filter((section) => section.hasMenuItem.length > 0);

  const data = { '@context': 'https://schema.org', '@type': 'Menu', name: `${config.brandName} menu`, hasMenuSection: sections };
  if (base) data.url = absolute(base, 'menu.html');
  if (config.locale) data.inLanguage = config.locale;
  return data;
}

/** The generated <head> block for one page. */
export function headBlock(page, html, { config, menuData, base }) {
  const { title, description } = pageText(html);
  const lines = [];
  const indexable = page.indexable && config.site?.allowIndexing === true;

  if (page.notFound && base) {
    // Served for any missing path (e.g. /menu/old): resolve assets from the site root.
    lines.push(`<base href="${escapeAttr(new URL(base).pathname)}">`);
  }
  if (!page.indexable) return lines.length ? wrap(lines) : null;

  if (!indexable) lines.push('<meta name="robots" content="noindex">');
  if (base) lines.push(`<link rel="canonical" href="${escapeAttr(absolute(base, page.path))}">`);

  lines.push(
    '<meta property="og:type" content="website">',
    `<meta property="og:site_name" content="${escapeAttr(config.brandName)}">`,
    `<meta property="og:title" content="${escapeAttr(title)}">`,
    `<meta property="og:description" content="${escapeAttr(description)}">`,
  );
  if (config.locale) lines.push(`<meta property="og:locale" content="${escapeAttr(ogLocale(config.locale))}">`);
  if (base) {
    lines.push(`<meta property="og:url" content="${escapeAttr(absolute(base, page.path))}">`);
    lines.push(
      `<meta property="og:image" content="${escapeAttr(absolute(base, OG_IMAGE.path))}">`,
      `<meta property="og:image:width" content="${OG_IMAGE.width}">`,
      `<meta property="og:image:height" content="${OG_IMAGE.height}">`,
      `<meta property="og:image:alt" content="${escapeAttr(OG_IMAGE.alt)}">`,
      '<meta name="twitter:card" content="summary_large_image">',
    );
  } else {
    lines.push('<meta name="twitter:card" content="summary">');
  }

  if (page.jsonLd === 'restaurant') lines.push(jsonLdScript(restaurantJsonLd(config, { base, isDemoMenu: menuData.IS_DEMO_MENU })));
  if (page.jsonLd === 'menu') {
    const menu = menuJsonLd(menuData, config, { base });
    if (menu) lines.push(jsonLdScript(menu));
  }

  return wrap(lines);
}

const wrap = (lines) => [START, ...lines, END].flatMap((line) => line.split('\n')).map((line) => `  ${line}`).join('\n');

/**
 * Put `block` into the page: replace an existing block, or insert it after the
 * description. A null block removes an existing one.
 */
export function applyBlock(html, block) {
  const existing = new RegExp(`[ \\t]*${escapeRegExp(START)}[\\s\\S]*?${escapeRegExp(END)}\\n?`);
  if (block === null) return html.replace(existing, '');
  if (existing.test(html)) return html.replace(existing, () => `${block}\n`);
  const description = /(<meta name="description" content="[^"]*">\n)/;
  if (!description.test(html)) throw new Error('no <meta name="description"> to insert after');
  return html.replace(description, (match) => `${match}${block}\n`);
}

const escapeRegExp = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function robotsTxt({ config, base }) {
  const lines = [
    '# Generated by tools/build-seo.mjs from js/config.js.',
    '# Pages that must stay out of search results say so with <meta name="robots">,',
    '# so crawlers are allowed to read them.',
    'User-agent: *',
    'Disallow:',
  ];
  if (base && config.site?.allowIndexing) lines.push('', `Sitemap: ${absolute(base, 'sitemap.xml')}`);
  return `${lines.join('\n')}\n`;
}

/** null when there is no URL or indexing is off (a sitemap needs absolute URLs). */
export function sitemapXml({ config, base }) {
  if (!base || !config.site?.allowIndexing) return null;
  const urls = PAGES.filter((page) => page.indexable).map((page) => `  <url><loc>${absolute(base, page.path)}</loc></url>`);
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`;
}

/** Facts worth adding before launch, for the build tool's warnings. */
export function launchWarnings(config) {
  const warnings = [];
  if (config.site?.allowIndexing && !siteBase(config)) warnings.push('allowIndexing is true but site.url is not set: no canonical URLs or sitemap.');
  if (config.site?.allowIndexing) {
    for (const key of ['address', 'phone', 'hours']) if (!config[key]) warnings.push(`${key} is not set: it is left out of the structured data.`);
  }
  return warnings;
}

/**
 * Everything to write. `read(file)` returns a page's current HTML.
 * @returns {{ files: Record<string, string>, remove: string[], warnings: string[] }}
 */
export function buildSeo({ config, menuData, read }) {
  const base = siteBase(config);
  const files = {};
  for (const page of PAGES) {
    const html = read(page.file);
    files[page.file] = applyBlock(html, headBlock(page, html, { config, menuData, base }));
  }
  files['robots.txt'] = robotsTxt({ config, base });
  const sitemap = sitemapXml({ config, base });
  const remove = [];
  if (sitemap) files['sitemap.xml'] = sitemap;
  else remove.push('sitemap.xml');
  return { files, remove, warnings: launchWarnings(config) };
}
